/**
 * Hand-written seed decisions for `npm run lexicon -- seed` (content authored in-session, no API).
 *
 * - SLASH: content items with «A / B» that are not a simple masculine/feminine pair → separate lemmas.
 * - GLOSSARY: reading glossary items are contextual («levanto-me logo», «hesitou») → dictionary lemma(s)
 *   with a lemma-level translation; the glossary form becomes an explicit form of the lemma.
 *   Items not listed here are kept as expressions (`pos: 'phrase'`) with the glossary translation.
 * - POS: part of speech for article-less vocab items where the heuristic would guess wrong.
 */
import type { LexPosValue } from '../../src/content/schema.ts'

export interface SeedSpec {
  lemma: string
  pos: LexPosValue
  /** Lemma-level meanings; omitted → taken from the content item. «; » separates meanings. */
  ru?: string
  gender?: 'm' | 'f' | 'mf'
  fem?: string
  forms?: string[]
}

const E = (lemma: string, pos: LexPosValue, ru?: string, gender?: 'm' | 'f' | 'mf', forms?: string[]): SeedSpec => ({
  lemma,
  pos,
  ...(ru ? { ru } : {}),
  ...(gender ? { gender } : {}),
  ...(forms ? { forms } : {}),
})

/** Masculine-only person noun with an explicit feminine form. */
const MF = (lemma: string, fem: string, ru?: string): SeedSpec => ({ lemma, pos: 'noun', gender: 'mf', fem, ...(ru ? { ru } : {}) })

