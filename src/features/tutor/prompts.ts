// Vocabulary theme
// ---------------------------------------------------------------------------

export function buildVocabPrompt(v: VocabTheme, extra?: TutorNotes): string {
  const level = v.level ?? 'A2'
  const article: Record<string, string> = { m: ' (m)', f: ' (f)', mf: ' (m/f)' }
  const words = v.words
    .slice(0, 60)
    .map((w) => `${w.pt}${w.gender && !/^(o|a|os|as)\s/i.test(w.pt) ? article[w.gender] : ''} — ${w.ru}`)
    .join('\n')
  return join(
    intro(`отработать со мной слова тематического словаря.\nТема: «${v.title}»${v.titlePt ? ` (${v.titlePt})` : ''}, уровень ${level}, ${v.words.length} слов.`, level),
    LANGUAGES,
    PT_PT_NORM,
    `ПЛАН СЕССИИ
1. Быстрый прогон: называй слова из списка по одному (pt → ru), я перевожу — так найдём незнакомые. Когда наберётся 15–20 слов, которые я не знаю или знаю нетвёрдо, переходи к шагу 2; с ними и работаем всю сессию.
2. Обратный перевод: ru → pt для этих слов. Существительные — всегда с артиклем (o / a), это важно; отмечай ошибки рода.
3. Возврат ошибок: слово, на котором я ошибся, спроси снова через 3–5 других слов, затем ещё раз ближе к концу — пока не отвечу верно дважды.
4. В контексте: 5–6 фраз по-португальски с пропуском, куда подходит одно из слов (бытовые ситуации в Португалии); потом 3 фразы на перевод с русского.
5. Мини-история: напиши историю из 5–6 предложений на pt-PT с 6–8 пропусками для слов сессии — я заполняю. Затем дай мне 5 слов, и я пишу свои 3–4 предложения; исправь их.
Веди счёт: «Счёт: 12/15».`,
    CORRECTIONS,
    notesBlock(extra),
    `СЛОВА (pt-PT — ru)\n${words}`,
    extra?.extraTasks?.length && `ДОПОЛНИТЕЛЬНЫЕ ЗАДАНИЯ:\n${numbered(extra.extraTasks)}`,
    COMMANDS,
    finale('число верных ответов с первой попытки за всю сессию', '\n   Отдельной строкой перечисли слова, которые нужно добавить в повторение.'),
    'Начинай сразу с первого слова быстрого прогона.',
  )
}

// ---------------------------------------------------------------------------
// Daily mixed conversation
// ---------------------------------------------------------------------------

export interface DailyPick {
  /** 1–2 weak (or next) grammar topics. */
  topics: Topic[]
  situation?: Situation
}

export function buildDailyPrompt({ topics, situation }: DailyPick): string {
  const level: Level = situation?.level ?? topics[0]?.level ?? 'A2'
  const topicBlocks = topics.map((t, i) =>
    join(
      `ТЕМА ${i + 1}: «${t.title}» (${t.titlePt}), ${t.level}\n${compressMarkdown(t.theory, topics.length > 1 ? 1300 : 1900)}`,
      t.commonErrors && `Типичные ошибки:\n${compressMarkdown(t.commonErrors, 450)}`,
    ),
  )
  const topicNames = topics.map((t) => `«${t.title}»`).join(' и ')
  const sit = situation
    ? join(
        `СИТУАЦИЯ: «${situation.title}» (${situation.titlePt}), ${situation.level}`,
        `Начало диалога-канвы:\n${dialogueScript({ ...situation, dialogue: situation.dialogue.slice(0, 6) }, false, 900)}`,
        situation.phrases.length > 0 && `Ключевые фразы:\n${phraseList(situation, 8)}`,
      )
    : ''
  return join(
    intro(
      `провести разговорную практику дня, в которой естественно нужны мои слабые темы${topics.length ? ` (${topicNames})` : ''}${situation ? ` и ситуация «${situation.title}»` : ''}.`,
      level,
    ),
    LANGUAGES,
    PT_PT_NORM,
    `ПЛАН СЕССИИ
1. Разминка (3–4 реплики): small talk по-португальски — как прошёл день, планы. Вопросы строй так, чтобы мне понадобились мои слабые темы. После каждой моей реплики — короткие исправления по-русски (до 2 пунктов), затем ответ и вопрос.
${situation ? `2. Сценка: ты — роль A в ситуации ниже, я — B. Меняй детали диалога-канвы и создавай моменты, где нужны слабые темы. Во время сцены не исправляй; после 6 моих реплик — «— Стоп, разбор —»: моя фраза → лучший вариант pt-PT → почему.` : '2. Продолжи разговор на одну бытовую тему (5–6 реплик), создавая моменты, где нужны слабые темы.'}
3. Прицельная тренировка: ${topics.length ? `по 3 коротких задания на каждую тему (${topicNames})` : '6 коротких заданий на ошибки из разговора'} — по одному, с разбором и счётом.
4. Если я повторяю одну и ту же ошибку — остановись и объясни правило подробнее (по материалу ниже).`,
    CORRECTIONS,
    ...topicBlocks,
    sit,
    COMMANDS,
    finale(
      'число верных ответов в прицельной тренировке (п. 3)',
      topics.length ? '\n   Отдельно по каждой теме — одна строка: «тема — уверенно / нужно повторить».' : '',
    ),
    'Начинай сразу: поприветствуй меня по-португальски и задай первый вопрос разминки.',
  )
}
