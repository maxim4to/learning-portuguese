function finale(scoreMeaning: string, extra = ''): string {
  return `ЗАВЕРШЕНИЕ
Когда план выполнен или я написал «стоп», подведи итог по-русски:
1. Что получилось хорошо (1–2 пункта).
2. Повторяющиеся ошибки: «было → правильно» + правило в одну строку (до 5).
3. Что повторить и следующий шаг.${extra}
4. Последней строкой, отдельным блоком кода (я скопирую её на сайт):
Итог: N/M · Оценка: легко | нормально | сложно · Повторить: <2–4 пункта>
N/M — ${scoreMeaning}. Оценка: от 85% — легко, 60–84% — нормально, ниже — сложно.`
}

function notesBlock(extra?: TutorNotes): string {
  return extra?.notes ? `ДОПОЛНИТЕЛЬНО ДЛЯ ЭТОЙ ТЕМЫ\n${extra.notes.trim()}` : ''
}

/** Joins non-empty blocks with blank lines. */
const join = (...blocks: (string | false | 0 | null | undefined)[]) =>
  blocks
    .filter((b): b is string => !!b && !!b.trim())
    .map((b) => b.trim())
    .join('\n\n')

const examplesList = (ex: readonly { pt: string; ru: string }[], n: number) =>
  bulleted(ex.slice(0, n).map((e) => `${stripInline(e.pt)} — ${stripInline(e.ru)}`))

