export function buildReadingPrompt(r: ReadingText, extra?: TutorNotes): string {
  const text = clip(r.paragraphs.map((p) => stripInline(p)).join('\n\n'), 3000)
  const glossary = r.glossary.map((g) => `${g.word} — ${g.ru}`).join('; ')
  return join(
    intro(`обсудить со мной прочитанный текст на португальском — понимание, мнение, словарь.\nТекст: «${r.title}», уровень ${r.level}. Я его уже прочитал и ответил на вопросы на сайте.`, r.level),
    LANGUAGES,
    PT_PT_NORM,
    `ПЛАН СЕССИИ
1. Пересказ: попроси меня пересказать текст по-португальски в 3–5 предложениях (если трудно — можно начать по-русски, тогда помоги перевести мой пересказ). Исправь и дай улучшенный вариант пересказа.
2. Понимание: 5–6 вопросов по-португальски по одному — от фактов к выводам («porquê?», «o que achas que…»). Отвечаю полными фразами; разбирай ошибки.
3. Мнение и личный опыт: 3–4 вопроса по теме текста, связанные с моей жизнью в Португалии. Здесь веди разговор: короткая реакция по-португальски + следующий вопрос.
4. Словарь: возьми 6–8 слов и выражений из глоссария, к каждому дай одно родственное слово или синоним (pt-PT) и попроси меня составить с ним свою фразу.
5. Грамматика текста: найди в тексте 1–2 конструкции уровня ${r.level} (времена, conjuntivo, клитики…), коротко объясни их и дай мне 3 задания на них.`,
    CORRECTIONS,
    notesBlock(extra),
    `ТЕКСТ\n${text}`,
    glossary && `ГЛОССАРИЙ: ${glossary}`,
    extra?.extraTasks?.length && `ДОПОЛНИТЕЛЬНЫЕ ЗАДАНИЯ:\n${numbered(extra.extraTasks)}`,
    COMMANDS,
    finale('число верных ответов на вопросы на понимание и в заданиях по словарю и грамматике (с первой попытки)'),
    'Начинай сразу: одной фразой по-русски объясни план и попроси меня пересказать текст.',
  )
}

