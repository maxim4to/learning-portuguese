interface TopicBudget {
  theory: number
  ptVsBr: number
  errors: number
  examples: number
  bank: number
}

const TOPIC_BUDGET: Record<TopicMode, TopicBudget> = {
  explain: { theory: 2100, ptVsBr: 450, errors: 650, examples: 4, bank: 6 },
  drill: { theory: 1700, ptVsBr: 300, errors: 650, examples: 0, bank: 10 },
  conversation: { theory: 1100, ptVsBr: 350, errors: 600, examples: 5, bank: 0 },
}

function topicMaterial(topic: Topic, b: TopicBudget, extra?: TutorNotes): string {
  const bank = b.bank ? pickExerciseLines([...topic.exercises, ...topic.miniTest], b.bank) : []
  const extraTasks = b.bank ? (extra?.extraTasks ?? []) : []
  const theory = compressMarkdown(topic.theory, b.theory)
  const cut = theory.includes('\n…') ? '; он сокращён — недостающее дополни сам' : ''
  return join(
    `МАТЕРИАЛ ТЕМЫ (конспект с моего сайта — опирайся на него, объясняй своими словами${cut})\n${theory}`,
    topic.ptVsBr && `pt-PT vs pt-BR:\n${compressMarkdown(topic.ptVsBr, b.ptVsBr)}`,
    topic.commonErrors && `Типичные ошибки русскоязычных:\n${compressMarkdown(topic.commonErrors, b.errors)}`,
    b.examples > 0 && topic.examples.length > 0 && `Примеры (pt-PT):\n${examplesList(topic.examples, b.examples)}`,
    bank.length + extraTasks.length > 0 &&
      `БАНК ЗАДАНИЙ — образцы стиля и сложности. Ответы после «→» — для тебя, мне их не показывай. Меняй лексику и ситуации, не повторяй дословно: эти задания я уже делал на сайте.\n${numbered([...bank, ...extraTasks])}`,
  )
}

