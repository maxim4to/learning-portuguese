export function buildTopicPrompt(topic: Topic, mode: TopicMode, extra?: TutorNotes): string {
  const head = `${TOPIC_TASK[mode]}.\nТема: «${topic.title}» (${topic.titlePt}), уровень ${topic.level}.`
  return join(
    intro(head, topic.level),
    LANGUAGES,
    PT_PT_NORM,
    TOPIC_PLAN[mode],
    CORRECTIONS,
    notesBlock(extra),
    topicMaterial(topic, TOPIC_BUDGET[mode], extra),
    COMMANDS,
    finale(TOPIC_SCORE[mode]),
    TOPIC_START[mode],
  )
}

