const SITUATION_SCORE: Record<SituationMode, string> = {
  roleplay: 'твоя оценка моих реплик по шкале из 10 (понятность, грамматика, уместность регистра)',
  dialogue: 'число верных ответов в контрольной из 10',
}

const SITUATION_START: Record<SituationMode, string> = {
  roleplay: 'Начинай сразу: строка-описание сцены по-русски и твоя первая реплика в роли A.',
  dialogue: 'Начинай сразу с первой части диалога.',
}

export function buildSituationPrompt(s: Situation, mode: SituationMode, extra?: TutorNotes): string {
  const task =
    mode === 'roleplay'
      ? `сыграть со мной сценку по бытовой ситуации, затем разобрать мои реплики.\nСитуация: «${s.title}» (${s.titlePt}), уровень ${s.level}.`
      : `разобрать со мной диалог по бытовой ситуации — фразы, грамматика, регистр — и проверить, смогу ли я сказать это сам.\nСитуация: «${s.title}» (${s.titlePt}), уровень ${s.level}.`
  const material = join(
    mode === 'roleplay'
      ? `ДИАЛОГ-КАНВА (A — твоя роль, B — моя; не цитируй его дословно)\n${dialogueScript(s, false, 2200)}`
      : `ДИАЛОГ (с переводом)\n${dialogueScript(s, true, 2800)}`,
    s.phrases.length > 0 && `КЛЮЧЕВЫЕ ФРАЗЫ — дай мне шанс использовать их${mode === 'roleplay' ? ' (сам их не подсказывай, пока я не застряну)' : ''}:\n${phraseList(s, mode === 'roleplay' ? 12 : 10)}`,
    s.vocab.length > 0 && `ЛЕКСИКА: ${vocabList(s, mode === 'roleplay' ? 25 : 18)}`,
    extra?.extraTasks?.length && `ДОПОЛНИТЕЛЬНЫЕ ЗАДАНИЯ:\n${numbered(extra.extraTasks)}`,
  )
  return join(
    intro(task, s.level),
    LANGUAGES,
    PT_PT_NORM,
    SITUATION_PLAN[mode](s),
    mode === 'roleplay'
      ? 'КАК ИСПРАВЛЯТЬ\nВо время сцены — не исправлять (см. план). В разборе — каждую мою реплику: исправленная версия целиком, жирным, и объяснение по-русски в 1–2 предложениях. Отмечай и ошибки, и неуклюжие кальки с русского.'
      : CORRECTIONS,
    notesBlock(extra),
    material,
    COMMANDS,
    finale(SITUATION_SCORE[mode]),
    SITUATION_START[mode],
  )
}

